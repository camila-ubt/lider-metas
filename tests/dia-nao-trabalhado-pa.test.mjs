import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";

const admin = "00000000-0000-0000-0000-000000000001";
const gestora = "00000000-0000-0000-0000-000000000002";
const vendedora = "00000000-0000-0000-0000-000000000003";
const inativa = "00000000-0000-0000-0000-000000000004";
const outra = "00000000-0000-0000-0000-000000000005";

test("gestão registra um dia não trabalhado no PA com segurança", async (t) => {
  const db = new PGlite();
  t.after(() => db.close());

  await db.exec(`
    create role anon; create role authenticated;
    create schema auth;
    create function auth.uid() returns uuid language sql stable as
      $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    grant usage on schema auth, public to authenticated, anon;

    create table auth.users (id uuid primary key);
    create table public.perfis (id uuid primary key, nome text, papel text, ativo boolean);
    create table public.usuarios_pa (
      id uuid primary key,
      nome text not null,
      numero_athos integer,
      tipo_usuario text not null,
      ativo boolean not null
    );
    create table public.lojas (
      id bigint primary key,
      codigo text,
      nome text,
      ativa boolean not null default true
    );
    create table public.dias_pa (
      id uuid primary key default gen_random_uuid(),
      usuario_id uuid not null,
      data date not null,
      situacao text not null check (situacao in
        ('trabalhado','nao_trabalhou','folga','falta','atestado','ferias')),
      observacao text,
      criado_em timestamptz not null default now(),
      atualizado_em timestamptz not null default now(),
      unique (usuario_id, data)
    );
    create table public.lancamentos_pa (
      id bigint generated by default as identity primary key,
      dia_id uuid not null,
      loja_id bigint not null,
      vendas integer not null,
      pecas integer not null,
      unique(dia_id, loja_id)
    );
    create table public.fechamentos_pa (
      mes date primary key,
      fechado_por uuid not null references auth.users(id),
      fechado_em timestamptz default now()
    );

    insert into auth.users values
      ('${admin}'),('${gestora}'),('${vendedora}'),('${inativa}'),('${outra}');
    insert into public.perfis values
      ('${admin}','Admin','admin',true),
      ('${gestora}','Gestora','gestora',true),
      ('${vendedora}','Vendedora','vendedora',true),
      ('${inativa}','Inativa','gestora',false);
    insert into public.usuarios_pa values
      ('${vendedora}','MELODY',17,'vendedora',true),
      ('${inativa}','INATIVA',18,'vendedora',false),
      ('${outra}','OUTRA',5,'vendedora',true);
    insert into public.lojas values (1,'AB','Adoro Bijoux',true);

    insert into public.dias_pa (usuario_id, data, situacao)
    select '${vendedora}', gs.dia::date, 'trabalhado'
    from generate_series('2026-10-01'::date, '2026-10-15'::date, '1 day') as gs(dia);

    insert into public.lancamentos_pa (dia_id, loja_id, vendas, pecas)
    select id,1,2,5 from public.dias_pa
    where usuario_id='${vendedora}' and data='2026-10-02';

    insert into public.dias_pa (usuario_id,data,situacao)
    values ('${vendedora}','2026-10-30','ferias');

    insert into public.fechamentos_pa(mes,fechado_por)
    values ('2026-09-01','${admin}');
  `);

  for (const arquivo of [
    "20260930162500_ferias_gestao_e_resumos_ativos.sql",
    "20261101212500_registrar_dia_nao_trabalhado_pa_gestao.sql",
  ]) {
    await db.exec(await readFile(new URL(`../supabase/migrations/${arquivo}`, import.meta.url), "utf8"));
  }

  const asUser = async (id) => {
    await db.exec("reset role; set role authenticated;");
    await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]);
  };

  const marcar = (usuario = vendedora, data = "2026-10-31") =>
    db.query("select public.registrar_dia_nao_trabalhado_pa_gestao($1,$2) as resultado",
      [usuario, data]);

  await t.test("a gestora completa o último dia de folga e destrava a apuração", async () => {
    await db.exec("reset role");
    let resumo = (await db.query(
      "select dias_validos,ultimo_dia_preenchido,premiacao_prevista from public.resumo_pa_mensal where usuario_id=$1",
      [vendedora],
    )).rows[0];
    assert.equal(resumo.dias_validos, 15);
    assert.equal(resumo.ultimo_dia_preenchido, false);
    assert.equal(resumo.premiacao_prevista, null);

    await asUser(gestora);
    const resposta = await marcar();
    assert.equal(resposta.rows[0].resultado.situacao, "nao_trabalhou");

    await db.exec("reset role");
    const dia = (await db.query(
      "select situacao, observacao from public.dias_pa where usuario_id=$1 and data='2026-10-31'",
      [vendedora],
    )).rows[0];
    assert.equal(dia.situacao, "nao_trabalhou");
    assert.equal(dia.observacao, null);

    resumo = (await db.query(
      "select dias_validos,ultimo_dia_preenchido,premiacao_prevista,pa from public.resumo_pa_mensal where usuario_id=$1",
      [vendedora],
    )).rows[0];
    assert.equal(resumo.dias_validos, 15);
    assert.equal(resumo.ultimo_dia_preenchido, true);
    assert.equal(resumo.premiacao_prevista, 100);
    assert.equal(Number(resumo.pa), 2.5);
  });

  await t.test("ação repetida mantém apenas um dia sem duplicar vendas", async () => {
    await asUser(admin);
    await marcar();
    await db.exec("reset role");
    const dias = (await db.query(
      "select count(*)::int as total from public.dias_pa where usuario_id=$1 and data='2026-10-31'",
      [vendedora],
    )).rows[0];
    assert.equal(dias.total, 1);
    const total = (await db.query("select count(*)::int as total from public.lancamentos_pa")).rows[0];
    assert.equal(total.total, 1);
  });

  await t.test("não altera dias com vendas, férias ou mês já fechado", async () => {
    await asUser(gestora);
    await assert.rejects(marcar(vendedora,"2026-10-02"), /tem vendas lançadas/);
    await assert.rejects(marcar(vendedora,"2026-10-30"), /já registrado como ferias/);
    await assert.rejects(marcar(vendedora,"2026-09-30"), /mês está fechado/);
    await db.exec("reset role");
    const dias = (await db.query(
      "select data::text,situacao from public.dias_pa where usuario_id=$1 and data in ('2026-10-02','2026-10-30') order by data",
      [vendedora],
    )).rows;
    assert.deepEqual(dias.map((x) => x.situacao), ["trabalhado", "ferias"]);
  });

  await t.test("nega vendedora, gestora inativa e usuário anônimo", async () => {
    for (const usuario of [vendedora, inativa]) {
      await asUser(usuario);
      await assert.rejects(marcar(vendedora, "2026-10-29"), /Somente a gestão ativa/);
    }
    await db.exec("reset role; set role anon;");
    await assert.rejects(marcar(), /permission denied/);
  });

  await t.test("valida vendedora ativa e proíbe datas futuras", async () => {
    await asUser(admin);
    await assert.rejects(marcar(inativa, "2026-10-29"), /Vendedora ativa não encontrada/);
    await assert.rejects(marcar(vendedora, "2099-01-01"), /data válida que não seja futura/);
  });

  await t.test("dia trabalhado sem vendas pode ser corrigido para não trabalhou", async () => {
    await asUser(admin);
    await marcar(vendedora, "2026-10-03");
    await db.exec("reset role");
    const dia = (await db.query(
      "select situacao from public.dias_pa where usuario_id=$1 and data='2026-10-03'",
      [vendedora],
    )).rows[0];
    assert.equal(dia.situacao, "nao_trabalhou");
    const resumo = (await db.query(
      "select dias_validos, premiacao_prevista from public.resumo_pa_mensal where usuario_id=$1",
      [vendedora],
    )).rows[0];
    assert.equal(resumo.dias_validos, 14);
    assert.equal(resumo.premiacao_prevista, 0);
  });
});
